function T([string]$Key) {
    $text = $script:UtaMessages[$script:UtaLang][$Key]
    if ($null -eq $text) { $text = $script:UtaMessages['en'][$Key] }
    if ($null -eq $text) { throw "Unknown UtaMaru UI text key: $Key" }
    return [string]$text
}
